/**
 * ロングテール用の年収レベル定義と、年収帯ごとの「特有の注意点」。
 * /take-home/{年収} と /furusato/{年収} の静的ページで使用する。
 *
 * 注意点は税率の境界・控除の壁・社会保険の上限など、
 * その年収帯に固有の事実のみを記載（推測・水増しはしない）。
 */

/** 300万〜1500万を50万円刻み（計25本） */
export const INCOME_MAN_VALUES: number[] = Array.from(
  { length: 25 },
  (_, i) => 300 + i * 50,
);

export interface IncomeLevel {
  /** 万円 */
  man: number;
  /** 円 */
  income: number;
  /** URL スラッグ（万円の数値） */
  slug: string;
}

export const INCOME_LEVELS: IncomeLevel[] = INCOME_MAN_VALUES.map((man) => ({
  man,
  income: man * 10_000,
  slug: String(man),
}));

const LEVEL_BY_SLUG = new Map(INCOME_LEVELS.map((l) => [l.slug, l]));

/** スラッグ（"500" など）から年収レベルを取得。存在しなければ undefined */
export function getIncomeLevel(slug: string): IncomeLevel | undefined {
  return LEVEL_BY_SLUG.get(slug);
}

/** 前後の年収レベル（内部リンク用） */
export function adjacentLevels(man: number): {
  prev?: IncomeLevel;
  next?: IncomeLevel;
} {
  const idx = INCOME_MAN_VALUES.indexOf(man);
  return {
    prev: idx > 0 ? INCOME_LEVELS[idx - 1] : undefined,
    next:
      idx >= 0 && idx < INCOME_LEVELS.length - 1
        ? INCOME_LEVELS[idx + 1]
        : undefined,
  };
}

